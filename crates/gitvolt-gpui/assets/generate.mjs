// Generates what the native UI embeds from what the web UI's npm packages hold, so both highlight
// and draw the same: run from ui/ after an npm install, `node ../crates/gitvolt-gpui/assets/generate.mjs`.
// - grammars/*.json.gz and src/diff/languages.rs: the grammars of ui/src/diff/shikiLanguages.ts,
//   which already leaves out the ones whose licenses GitVolt can't take, plus its own glsl and tcl;
// - themes.json: the ten app themes, as ui/src/theme/themes.ts resolves them;
// - editor-themes/*.json: each one's editor theme (tm-themes, and the web UI's own Darcula): its token colours and
//   the colours Monaco draws an editor with, its own or Monaco's defaults for its kind;
// - emoji.json.gz: gemoji's list, for rendered Markdown's shortcodes and the field's completion;
// - fonts/JetBrainsMono-Latin-400.ttf: the bundled editor font's Latin face, unwrapped from its WOFF;
// - src/diff/testdata/shiki-golden.json: what Shiki colours the samples, for the engine's test;
// - src/testdata/themes-golden.json: what custom.ts makes of a custom theme on each base, for theme.rs's test.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { registerHooks } from 'node:module';
import { gzipSync, inflateSync } from 'node:zlib';

const out = new URL('./', import.meta.url);
const ui = new URL('file://' + process.cwd() + '/');
const read = (rel) => readFileSync(new URL(rel, ui));

const registry = read('src/diff/shikiLanguages.ts').toString();
const entries = [...registry.matchAll(/\{ id: '([^']+)', name: '(?:[^'\\]|\\.)*'(?:, aliases: \[([^\]]*)\])?, import: \(\) => (own\(import\('\.\/grammars\/([^']+)'\)\)|import\('shiki\/langs\/([^']+)\.mjs'\))/g)];
rmSync(new URL('grammars/', out), { recursive: true, force: true });
mkdirSync(new URL('grammars/', out), { recursive: true });
// Each language's module lists what Shiki loads with it: other languages, and internal grammars (Vue's
// directives, Angular's templates, the ES tags) that aren't languages of their own. An injection needs
// them, so they're embedded too, under their names.
const { pathToFileURL } = await import('node:url');
const parsed = [];
const known = new Set();
for (const [, id, aliases, , own, lang] of entries) {
  const json = own ? read(`src/diff/grammars/${own}`) : read(`node_modules/tm-grammars/grammars/${lang}.json`);
  const scope = JSON.parse(json).scopeName;
  known.add(scope);
  parsed.push({ id, aliases, own, lang, json, scope });
}
const injectTo = new Map();
const internal = new Map();
for (const p of parsed) {
  p.deps = [];
  if (!p.lang) continue;
  for (const g of (await import(pathToFileURL(new URL(`node_modules/@shikijs/langs/dist/${p.lang}.mjs`, ui).pathname).href)).default) {
    if (!p.deps.includes(g.scopeName)) p.deps.push(g.scopeName);
    if (g.injectTo) injectTo.set(g.scopeName, g.injectTo);
    if (!known.has(g.scopeName)) internal.set(g.scopeName, g);
  }
}
// Its injections' order decides a tie, and the engine's JSON doesn't keep a key order.
const withOrder = (json) => {
  const g = JSON.parse(json);
  return g.injections ? JSON.stringify({ ...g, injectionOrder: Object.keys(g.injections) }) : json;
};
const names = (list) => (list ?? []).map((n) => `"${n}"`).join(', ');
const rows = [];
for (const { id, aliases, json, scope, deps } of parsed) {
  writeFileSync(new URL(`grammars/${id}.json.gz`, out), gzipSync(withOrder(json), { level: 9 }));
  const alias = [...(aliases ?? '').matchAll(/'([^']+)'/g)].map((m) => m[1]);
  rows.push(`    Lang { id: "${id}", scope: "${scope}", aliases: &[${names(alias)}], inject_to: &[${names(injectTo.get(scope))}], deps: &[${names(deps)}], gz: include_bytes!("../../assets/grammars/${id}.json.gz") },`);
}
for (const [scope, g] of internal) {
  writeFileSync(new URL(`grammars/${g.name}.json.gz`, out), gzipSync(JSON.stringify(g), { level: 9 }));
  rows.push(`    Lang { id: "${g.name}", scope: "${scope}", aliases: &[], inject_to: &[${names(injectTo.get(scope))}], deps: &["${scope}"], gz: include_bytes!("../../assets/grammars/${g.name}.json.gz") },`);
}
writeFileSync(new URL('../src/diff/languages.rs', out), `// Generated by assets/generate.mjs: do not edit.\n\nuse super::textmate::Lang;\n\npub const LANGS: &[Lang] = &[\n${rows.join('\n')}\n];\n`);

