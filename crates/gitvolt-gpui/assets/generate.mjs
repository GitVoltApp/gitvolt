// WOFF 1.0: a header, a table directory, each table zlib-deflated unless that wouldn't shrink it.
const woff = read('node_modules/@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff');
const count = woff.readUInt16BE(12);
const tables = [];
for (let i = 0; i < count; i++) {
  const at = 44 + i * 20;
  const [tag, offset, comp, orig, sum] = [woff.subarray(at, at + 4), woff.readUInt32BE(at + 4), woff.readUInt32BE(at + 8), woff.readUInt32BE(at + 12), woff.readUInt32BE(at + 16)];
  const raw = woff.subarray(offset, offset + comp);
  tables.push({ tag, sum, data: comp === orig ? raw : inflateSync(raw) });
}
const floor = Math.floor(Math.log2(count));
const head = Buffer.alloc(12 + count * 16);
woff.copy(head, 0, 4, 8);
head.writeUInt16BE(count, 4);
head.writeUInt16BE(16 * 2 ** floor, 6);
head.writeUInt16BE(floor, 8);
head.writeUInt16BE(count * 16 - 16 * 2 ** floor, 10);
let at = head.length;
const parts = [head];
tables.forEach((t, i) => {
  t.tag.copy(head, 12 + i * 16);
  head.writeUInt32BE(t.sum, 16 + i * 16);
  head.writeUInt32BE(at, 20 + i * 16);
  head.writeUInt32BE(t.data.length, 24 + i * 16);
  const pad = Buffer.alloc((4 - (t.data.length % 4)) % 4);
  parts.push(t.data, pad);
  at += t.data.length + pad.length;
});
writeFileSync(new URL('fonts/JetBrainsMono-Latin-400.ttf', out), Buffer.concat(parts));

