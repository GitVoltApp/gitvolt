// Generates what the native UI embeds from what the web UI's npm packages hold, so both highlight
// and draw the same: run from ui/ after an npm install, `node ../crates/gitvolt-gpui/assets/generate.mjs`.
// - grammars/*.json.gz and src/diff/languages.rs: the grammars of ui/src/diff/shikiLanguages.ts,
//   which already leaves out the ones whose licenses GitVolt can't take, plus its own glsl and tcl;
// - dark-plus.json: Default Dark's token colours (tm-themes);
// - fonts/JetBrainsMono-Latin-400.ttf: the bundled editor font's Latin face, unwrapped from its WOFF;
// - src/diff/testdata/shiki-golden.json: what Shiki colours the samples, for the engine's test.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { gzipSync, inflateSync } from 'node:zlib';

const out = new URL('./', import.meta.url);
const ui = new URL('file://' + process.cwd() + '/');
const read = (rel) => readFileSync(new URL(rel, ui));

const registry = read('src/diff/shikiLanguages.ts').toString();
const entries = [...registry.matchAll(/\{ id: '([^']+)', name: '(?:[^'\\]|\\.)*'(?:, aliases: \[([^\]]*)\])?, import: \(\) => (own\(import\('\.\/grammars\/([^']+)'\)\)|import\('shiki\/langs\/([^']+)\.mjs'\))/g)];
rmSync(new URL('grammars/', out), { recursive: true, force: true });
mkdirSync(new URL('grammars/', out), { recursive: true });
const rows = [];
for (const [, id, aliases, , own, lang] of entries) {
  const json = own ? read(`src/diff/grammars/${own}`) : read(`node_modules/tm-grammars/grammars/${lang}.json`);
  const scope = JSON.parse(json).scopeName;
  writeFileSync(new URL(`grammars/${id}.json.gz`, out), gzipSync(json, { level: 9 }));
  const names = [...(aliases ?? '').matchAll(/'([^']+)'/g)].map((m) => `"${m[1]}"`).join(', ');
  rows.push(`    Lang { id: "${id}", scope: "${scope}", aliases: &[${names}], gz: include_bytes!("../../assets/grammars/${id}.json.gz") },`);
}
writeFileSync(new URL('../src/diff/languages.rs', out), `// Generated by assets/generate.mjs: do not edit.\n\nuse super::textmate::Lang;\n\npub const LANGS: &[Lang] = &[\n${rows.join('\n')}\n];\n`);

const theme = JSON.parse(read('node_modules/tm-themes/themes/dark-plus.json'));
writeFileSync(new URL('dark-plus.json', out), JSON.stringify({ name: theme.name, foreground: theme.colors['editor.foreground'], tokenColors: theme.tokenColors }));

// WOFF 1.0: a header, a table directory, each table zlib-deflated unless that wouldn't shrink it.
const woff = read('node_modules/@fontsource/jetbrains-mono/files/jetbrains-mono-latin-400-normal.woff');
const count = woff.readUInt16BE(12);
const tables = [];
for (let i = 0; i < count; i++) {
  const at = 44 + i * 20;
  const [tag, offset, comp, orig, sum] = [woff.subarray(at, at + 4), woff.readUInt32BE(at + 4), woff.readUInt32BE(at + 8), woff.readUInt32BE(at + 12), woff.readUInt32BE(at + 16)];
  const raw = woff.subarray(offset, offset + comp);
  tables.push({ tag, sum, data: comp === orig ? raw : inflateSync(raw) });
}
const floor = Math.floor(Math.log2(count));
const head = Buffer.alloc(12 + count * 16);
woff.copy(head, 0, 4, 8);
head.writeUInt16BE(count, 4);
head.writeUInt16BE(16 * 2 ** floor, 6);
head.writeUInt16BE(floor, 8);
head.writeUInt16BE(count * 16 - 16 * 2 ** floor, 10);
let at = head.length;
const parts = [head];
tables.forEach((t, i) => {
  t.tag.copy(head, 12 + i * 16);
  head.writeUInt32BE(t.sum, 16 + i * 16);
  head.writeUInt32BE(at, 20 + i * 16);
  head.writeUInt32BE(t.data.length, 24 + i * 16);
  const pad = Buffer.alloc((4 - (t.data.length % 4)) % 4);
  parts.push(t.data, pad);
  at += t.data.length + pad.length;
});
writeFileSync(new URL('fonts/JetBrainsMono-Latin-400.ttf', out), Buffer.concat(parts));

// Lucide (ISC), as the web UI's lucide-react draws them, and its own status glyphs (StatusIcon.tsx).
const ICONS = ['archive', 'arrow-down', 'arrow-up', 'bell', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'chevrons-down-up', 'cloud', 'command', 'download', 'folder-open', 'folder-plus', 'git-branch', 'git-branch-plus', 'git-graph', 'house', 'laptop', 'list', 'list-tree', 'menu', 'minus', 'pilcrow', 'pin', 'redo-2', 'search', 'settings', 'shield-check', 'square', 'tag', 'tree-pine', 'undo-2', 'unfold-vertical', 'upload', 'text-wrap', 'x'];
rmSync(new URL('icons/', out), { recursive: true, force: true });
mkdirSync(new URL('icons/', out), { recursive: true });
const svg = (box, width, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${box}" height="${box}" viewBox="0 0 ${box} ${box}" fill="none" stroke="currentColor" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`;
for (const name of ICONS) {
  const nodes = (await import(new URL(`node_modules/lucide-react/dist/esm/icons/${name}.mjs`, ui))).__iconData.node;
  const body = nodes.map(([tag, attrs]) => { const { key, ...rest } = attrs; return `<${tag} ${Object.entries(rest).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`; }).join('');
  writeFileSync(new URL(`icons/${name}.svg`, out), svg(24, 2, body));
}
const GLYPHS = {
  added: '<path d="M8 3v10M3 8h10"/>',
  modified: '<path d="M10.5 2.5l3 3L6 13H3v-3z"/><path d="M9 4l3 3"/>',
  deleted: '<path d="M3 8h10"/>',
  renamed: '<path d="M3 13V9.5A4.5 4.5 0 0 1 7.5 5H13"/><path d="M10 2l3 3-3 3"/>',
  conflicted: '<path d="M8 3v6"/><path d="M8 12.5v.5"/>',
};
for (const [name, body] of Object.entries(GLYPHS)) writeFileSync(new URL(`icons/status-${name}.svg`, out), svg(16, 1.5, body));
writeFileSync(new URL('../src/icons.rs', out), `// Generated by assets/generate.mjs: do not edit.\n\npub fn load(path: &str) -> Option<&'static [u8]> {\n    Some(match path {\n${[...ICONS, ...Object.keys(GLYPHS).map((g) => `status-${g}`)].map((n) => `        "icons/${n}.svg" => include_bytes!("../assets/icons/${n}.svg"),`).join('\n')}\n        _ => return None,\n    })\n}\n`);

